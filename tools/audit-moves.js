// Move-table fairness audit (spec §5.2c-d, §17.1): frame data, tells, reposition warnings and answers for every boss move.
// `node tools/audit-moves.js` prints the report; `--write` also saves it to docs/fairness.md. Answers are verified by
// simulation (tools/answers.js). A flag must carry a judgement below, or tests/fairness.test.js fails.
'use strict';
const fs = require('fs'), path = require('path');
const { verifier, first } = require('./answers');

const RULES = { minStartup: .2, minHeavyRecovery: .3, minRepositionWarning: .25 };
// judged flags: the reason a flagged move stays as it is (or what M2 changed)
const JUDGED = {
  b_kick: 'fast (0.13 s) but light (5): holding block answers it.',
  k_flurry: 'fast (0.08 s) but light (3 × 4): holding block answers every hit.',
  k_stab: 'fast (0.11 s) but light (6): holding block answers it.',
  k_low: 'fast (0.17 s) knockdown sweep, kept fast as Kasumi’s identity: crouch-block (held) answers it, its tell glints from 0.02 s. M2 raised its recovery 0.23 → 0.30 s.',
};
const NOTES = {
  k_vanish: 'teleport to hit 0.10 s; the destination marker shows from the vanish (0.50 s before the hit) and the Block key turns with her.',
  y_phase: 'teleport to hit 0.17 s; marker 0.56 s before the hit. M2 raised recovery 0.26 → 0.30 s.',
  y_rise: 'M2 raised recovery 0.26 → 0.30 s.', a_sweep: 'M2 raised recovery 0.29 → 0.30 s.',
};

function frameData(MV, id) {
  const m = MV[id], w = m.hit || [[m.proj.t, (m.proj2 || m.proj).t]], parts = [m, ...(m.win || []).filter(Boolean).map(x => Object.assign({}, m, x)), m.proj, m.proj2].filter(x => x && x.dmg != null);
  const dmg = Math.max(...parts.map(x => x.dmg)), kd = parts.some(x => x.kd); // a string or volley is as heavy as its heaviest part
  const startup = first(m), end = w[w.length - 1][1], active = w.reduce((a, x) => a + x[1] - x[0], 0);
  const hits = m.hit ? m.hit.map((x, i) => m.win && m.win[i] && m.win[i].dmg || m.dmg) : [m.proj, m.proj2].filter(Boolean).map(x => x.dmg);
  const heavyAt = m.hit ? m.hit.find((x, i) => { const y = m.win && m.win[i] ? Object.assign({}, m, m.win[i]) : m; return y.dmg >= 10 || y.kd; }) : null, tellBy = heavyAt ? heavyAt[0] : startup; // the tell warns of the heavy step
  return { id, startup, active, recovery: m.dur - end, reach: m.proj ? 'proj' : m.reach, dmg: hits.join(' + '), perHit: dmg, kd,
    zone: m.zone || m.proj.zone, heavy: dmg >= 10 || kd, tell: m.tell || null, tellLead: m.tell ? tellBy - m.tell[0] : null,
    mark: m.mark || null, warning: m.mark ? startup - m.mark[0] : null, teleportGap: m.mark ? startup - m.mark[1] : null, answers: m.answers || [] };
}

function flags(f) {
  const out = [], e = 1e-9;
  if (f.startup < RULES.minStartup - e) out.push(`startup ${f.startup.toFixed(2)} s < ${RULES.minStartup}`);
  if (f.heavy && f.recovery < RULES.minHeavyRecovery - e) out.push(`heavy, recovery ${f.recovery.toFixed(2)} s < ${RULES.minHeavyRecovery}`);
  if (f.heavy && !f.tell) out.push('heavy without a tell');
  if (f.mark && f.warning < RULES.minRepositionWarning - e) out.push(`reposition warning ${f.warning.toFixed(2)} s < ${RULES.minRepositionWarning}`);
  if (f.answers.length < 2) out.push('fewer than two answers');
  return out;
}

async function audit({ verify = true } = {}) {
  const v = await verifier(), bosses = v.game.BOSSES, rows = [];
  for (const b of bosses) for (const id of [...b.moves, b.phase && b.phase.move].filter(Boolean)) {
    const f = Object.assign(frameData(v.MV, id), { boss: b.id, phase: !!b.phase && b.phase.move === id }), d = v.distance(id);
    f.verified = verify && d != null ? f.answers.filter(a => v.works(id, a, d)) : null;
    f.flags = flags(f); f.judged = JUDGED[id] || null; f.note = NOTES[id] || null;
    rows.push(f);
  }
  return rows;
}

function markdown(rows) {
  const s = x => x == null ? '—' : typeof x === 'number' ? x.toFixed(2) : x, L = [];
  L.push('# Boss move fairness audit', '', 'Generated by `node tools/audit-moves.js --write` (M2). Times in seconds. Rules (spec §5.2): startup ≥ 0.20 s unless holding block answers it; heavy moves (dmg ≥ 10 or knockdown) recover ≥ 0.30 s and carry a tell (shape + audio + pose cue); a reposition shows its destination ≥ 0.25 s before the hit; every move has ≥ 2 answers, each verified by simulation (`tools/answers.js`).', '');
  L.push('| move | boss | startup | active | recovery | reach | dmg | zone | KD | tell | tell lead | answers (verified) | flags · judgement |', '|---|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const f of rows) L.push(`| ${f.id}${f.phase ? ' (phase 2)' : ''} | ${f.boss} | ${s(f.startup)} | ${s(f.active)} | ${s(f.recovery)} | ${f.reach} | ${f.dmg} | ${f.zone} | ${f.kd ? 'yes' : ''} | ${f.tell ? f.tell.join('–') : ''} | ${s(f.tellLead)} | ${f.answers.join(', ')}${f.verified ? (f.verified.length === f.answers.length ? ' ✓' : ` ✗ only ${f.verified.join(', ')}`) : ''} | ${[...f.flags, f.judged, f.note].filter(Boolean).join(' · ')} |`);
  return L.join('\n') + '\n';
}

module.exports = { audit, flags, frameData, RULES, JUDGED };

if (require.main === module) (async () => {
  const md = markdown(await audit());
  process.stdout.write(md);
  if (process.argv.includes('--write')) fs.writeFileSync(path.join(__dirname, '..', 'docs', 'fairness.md'), md);
})();
