// Visual / data consistency (spec §6.3): for every bladed move, the weapon tip's furthest forward point during the active
// window against the distance the hit test really reaches (reach x scale + 20 px of the defender). Off by more than 25% is
// flagged. `node tools/reach-check.js --write` saves docs/reach-check.md; tests/reach.test.js fails on a flag not listed below.
'use strict';
const fs = require('fs'), path = require('path');
const { boot } = require('./harness');
const tipLen = k => k.spear ? 132 : k.club ? 150 : k.nagi ? 170 : k.blen || 112;
const KICKS = new Set(['kick', 'round', 'sweepK', 'airKick', 'b_kick', 'k_low']);
// shipped boss moves the 1-D check does not fit, judged and kept (they are tuned by play, and the owner reviews boss changes)
const KNOWN = {
  'gekko.g_dragon': 'a 1,700 px/s lunge: the spear lands the hit while the body is still travelling',
  'akuma.a_leap': 'a leap: the hit comes from above at the landing point',
  'tetsugoro.m_low': 'a long low sweep of the club; the low zone, not the tip, decides it',
  'shirasagi.y_rise': 'a rising cut: it strikes upward (high zone), so a forward-reach check does not apply',
};

async function check() {
  const { game } = await boot(), rows = [];
  const meas = (name, m, def) => {
    if (!m.hit || !m.reach) return;
    let best = -1e9;
    for (const w of m.hit) for (let t = w[0]; t <= w[1] + 1e-9; t += 1 / 120) {
      const p = Object.assign({}, game.lab.P(), game.lab.kf(t, m.fr(def.guard)), def.wk, { x: 0, f: 1, s: def.s, lift: 0 });
      best = Math.max(best, game.bladePt(p, def.kind, tipLen(def.kind))[0]);
    }
    const R = m.reach * def.s + 20, r = best / R;
    rows.push({ name, tip: Math.round(best), reach: Math.round(R), ratio: +r.toFixed(2), flag: r < .75 || r > 1.25, known: KNOWN[name] || null });
  };
  for (const n of ['slash', 'slash2', 'slash3', 'lunge', 'low', 'air']) meas('katana.' + n, game.MV[n], game.HERO_D);
  for (const [id, w] of Object.entries(game.GEAR.weapons)) {
    if (id === 'katana' || w.class) continue; // variants share their class's moves (1.7)
    const d = game.derive(Object.assign({}, game.SV, { gear: { owned: [id], equipped: { weapon: id, charm: null }, tiers: { [id]: 1 } } }));
    const def = Object.assign({}, game.HERO_D, { kind: d.kind, guard: d.guard, wk: d.wk });
    for (const n of Object.keys(w.moves)) meas(id + '.' + n, d.ov[n], def);
  }
  for (const b of game.BOSSES) for (const n of [...b.moves, b.phase && b.phase.move].filter(Boolean)) if (!KICKS.has(n)) meas(b.id + '.' + n, game.MV[n], b);
  for (const f of Object.values(game.FOES)) for (const n of f.moves) if (!KICKS.has(n) && !rows.some(r => r.name.endsWith('.' + n))) meas(f.id + '.' + n, game.MV[n], f);
  return rows;
}
module.exports = { check, KNOWN };
if (require.main === module) (async () => {
  const rows = await check(), L = ['# Reach check (spec §6.3)', '', 'Generated by `node tools/reach-check.js --write`. The weapon tip’s furthest forward point in the active window against the distance the hit test reaches (reach × scale + 20 px). More than 25% off is flagged.', '',
    '| move | tip px | reach px | ratio | |', '|---|---|---|---|---|'];
  for (const r of rows) L.push(`| ${r.name} | ${r.tip} | ${r.reach} | ${r.ratio} | ${r.flag ? (r.known ? 'known: ' + r.known : '**flagged**') : ''} |`);
  const md = L.join('\n') + '\n'; process.stdout.write(md);
  if (process.argv.includes('--write')) fs.writeFileSync(path.join(__dirname, '..', 'docs', 'reach-check.md'), md);
})();
